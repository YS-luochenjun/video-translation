from __future__ import annotations

from . import media, workflow
from .common import ROOT, file_hash, get_run, read_json, require, require_number, write_json


def create_demo(name, route, seconds=8):
    import re
    require(bool(re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,79}", name)), "Invalid run id")
    require_number(seconds, "demo duration", minimum=1, maximum=180)
    require(not (ROOT / "runs" / name).exists(), "Demo run already exists")
    work = ROOT / "work/demo-fixture" / name
    work.mkdir(parents=True, exist_ok=True)
    source = work / "english-ad.mp4"
    # This is a generated test fixture, not a customer ad or evidence of model quality.
    ass = "\n".join([
        "[Script Info]", "ScriptType: v4.00+", "PlayResX: 1280", "PlayResY: 720",
        "[V4+ Styles]", "Format: Name,Fontname,Fontsize,PrimaryColour,SecondaryColour,OutlineColour,BackColour,Bold,Italic,Underline,StrikeOut,ScaleX,ScaleY,Spacing,Angle,BorderStyle,Outline,Shadow,Alignment,MarginL,MarginR,MarginV,Encoding",
        "Style: Default,Arial,48,&H002A3025,&H002A3025,&H00000000,&H00000000,0,0,0,0,100,100,0,0,1,0,0,5,0,0,0,1",
        "[Events]", "Format: Layer,Start,End,Style,Name,MarginL,MarginR,MarginV,Effect,Text",
        r"Dialogue: 0,0:00:00.00,0:00:08.00,Default,,0,0,0,,{\an5\pos(640,100)\fs28\b1}FRESH",
        r"Dialogue: 0,0:00:00.00,0:00:08.00,Default,,0,0,0,,{\an5\pos(640,240)\fs64\b1}A LITTLE BREAK",
        r"Dialogue: 0,0:00:00.00,0:00:08.00,Default,,0,0,0,,{\an5\pos(640,340)\fs36}Brew your next idea.",
        r"Dialogue: 0,0:00:00.00,0:00:08.00,Default,,0,0,0,,{\an5\pos(640,560)\fs32\c&HFFFFFF&}Try it today", ""])
    ass = ass.replace("0:00:08.00", media.ass_time(seconds))
    (work / "source.ass").write_text(ass, encoding="utf-8-sig")
    media.ffmpeg(["-f", "lavfi", "-i", f"color=c=0xEAF0E8:s=1280x720:r=30:d={seconds}", "-f", "lavfi", "-i",
                  f"sine=frequency=330:sample_rate=48000:duration={seconds}", "-vf",
                  "drawbox=x=440:y=510:w=400:h=100:color=0x284538:t=fill," + media.ass_filter('source.ass'),
                  "-af", "volume=0.025", "-c:v", "libx264", "-pix_fmt", "yuv420p", "-c:a", "aac", source.name], cwd=work)
    workflow.create_run(source, "zh-CN", "将英文短广告翻译为自然中文；保留 FRESH 品牌、配色和节奏。", name)
    run = get_run(name)
    workflow.analyze(run)
    inventory = read_json(run / "analysis/inventory.json")
    (run / "analysis/fixture-provenance.txt").write_text(
        "Synthetic fixture generated by src/video_localizer/demo.py. Exactly three English copy instances and FRESH brand.\n"
        f"All remain fixed at the same position from 0 to {seconds} seconds. Audio is a generated sine wave with no speech.\n"
        "This known fixture permits deterministic annotations; arbitrary customer videos require actual analysis.\n", encoding="utf-8")
    inventory["coverage"] = {kind: {"status": "reviewed", "method": "Known generated fixture specification; not automatic OCR/ASR",
                             "evidence": ["analysis/fixture-provenance.txt", "analysis/contact-sheet.jpg"]}
                             for kind in ("visual", "speech", "timeline")}
    for shot in inventory["shots"]:
        shot["description"] = "Static minimalist FRESH beverage advertisement on a pale green background; three fixed copy lines and one brand."
    common = {"start": 0, "end": seconds, "background_is_static": True,
              "evidence": ["analysis/shot-001.jpg", "analysis/fixture-provenance.txt"], "action": "solid_overlay",
              "background": "#EAF0E8", "text_color": "#25302A", "reason": "Known flat static background permits exact copy replacement"}
    inventory["text_instances"] = [
        {**common, "id": "t001", "source_text": "A LITTLE BREAK", "target_text": "给自己片刻放松", "bbox": [280, 180, 720, 120], "font_size": 60},
        {**common, "id": "t002", "source_text": "Brew your next idea.", "target_text": "灵感，从这一杯开始。", "bbox": [280, 305, 720, 80], "font_size": 36},
        {**common, "id": "t003", "source_text": "Try it today", "target_text": "现在就尝尝", "bbox": [440, 510, 400, 100], "font_size": 32, "background": "#284538", "text_color": "#FFFFFF"},
        {**common, "id": "t004", "source_text": "FRESH", "target_text": "FRESH", "bbox": [540, 75, 200, 50], "action": "preserve", "reason": "Brand exception, explicitly preserved"}
    ]
    inventory["audio"] = {"has_speech": False, "strategy": "preserve", "reason": "Known fixture contains only a quiet synthesized tone; no foreign speech"}
    from .knowledge import context_for, retrieve
    entries = retrieve(context_for(read_json(run / 'inputs/request.json'), inventory, ROOT), root=ROOT)
    method = next(e['id'] for e in entries if e['id'].startswith('route-selection-'))
    inventory['routing_assessment'] = {'version': 1, 'primary_type': 'onscreen_text_led',
        'reason': 'Known generated fixture: independent copy and nonverbal sine tone; not a real-video judgment',
        'evidence': ['analysis/fixture-provenance.txt'], 'method_choices': [{
            'domain': 'visual', 'method_id': method, 'reason': 'Known static flat fixture permits exact composition',
            'alternative': 'Inspect another local repair if the generated surface changes',
            'switch_when': 'Actual encoded fixture shows a copy/background mismatch',
            'stop_when': 'Synthetic contract checks complete; no media acceptance claimed'}]}
    write_json(run / "analysis/inventory.json", inventory)
    # Deterministic annotations apply ONLY to this generated fixture. Real ads
    # require Codex observations and original-video references before capture.
    from . import fonts, source_styles
    styles = []
    for item in inventory['text_instances']:
        if item['action'] == 'preserve':
            continue
        bold = item['id'] == 't001'
        colour = item.get('text_color', '#25302A')
        item['display'] = {'font_asset': fonts.bind(run, fonts.default_family(locale='zh-CN'), bold, item['target_text']),
                           'font_size': item['font_size'], 'min_font_size': 20, 'bold': bold, 'italic': False,
                           'color': colour, 'outline': 0, 'align': 'center'}
        item['style_treatment'] = {'route': 'typeset', 'reason': 'Known synthetic flat-text fixture; not a real-ad quality claim',
            'font_choice_reason': 'Actual target-script font; source sans-serif hierarchy retained in this generated fixture',
            'adaptations': {}}
        styles.append({'id': item['id']+'-style', 'instance_ids': [item['id']],
            'observation': 'Known generated ASS specification; no automatic source-font recognition',
            'appearance': {'kind': 'plain', 'font_class': 'sans', 'weight': 'bold' if bold else 'regular',
                           'italic': False, 'color': colour, 'outline_layers': [], 'effects': 'none'},
            'layout': {'bbox': item['bbox'], 'line_count': 1, 'align': 'center'},
            'motion': {'kind': 'static', 'observation': 'Known stationary fixture for its entire interval'},
            'protected_content': 'FRESH brand and the original background outside the text region'})
    write_json(run/'analysis/inventory.json', inventory)
    write_json(run/'inputs/source-style-fixture.json', {'source_sha256': inventory['source_sha256'],
               'observed_by': 'Synthetic fixture specification only; no customer-video observations', 'styles': styles})
    source_styles.capture(run, 'inputs/source-style-fixture.json', apply=True)
    result = workflow.build_plan(run, None if route == "local_overlay" else route)
    if route == "local_overlay":
        result.update(workflow.render(run))
    return {"run": name, "fixture": "synthetic_not_real_ad", **result}

