"""Preview and archive strictly boilerplate-only reflection records.

This rejects treating a placeholder as a lesson. It never rejects the video,
changes its historical quality outcome or deletes its independent evidence.
"""
from pathlib import Path

from .common import object_hash, require, file_hash
from .knowledge_review import queue,review,archive_preview,archive
from .candidate_index import refresh

GENERATED_KEYS={'id','status','created_at','scope','case','outcome','hypothesis','evidence','limitations',
                'company_preference','promotion','knowledge_class','evidence_boundary'}
PROMOTION='Requires scoped evidence and developer/company review; not loaded by retrieval'
BOUNDARY='Technical observation and hashes; raw private case is not needed to read this hypothesis. Activation requires independently packaged reviewed evidence.'


def preview(root, source_hashes):
    require(bool(source_hashes),'Select the audited sources explicitly')
    selected=[]
    for row in queue(root):
        value=row['record'];scope=value.get('scope',{});evidence=value.get('evidence',{})
        if not isinstance(scope,dict) or scope.get('source_sha256') not in source_hashes:continue
        if row['previous_review'] or row['prior_adoptions']:continue
        # Do not make semantic judgments about custom prose, actual limitations,
        # user feedback or new evidence digests, even if they have no hypothesis.
        if (not set(value)<=GENERATED_KEYS or value.get('hypothesis')!='Needs an evidence-backed lesson'
            or value.get('limitations')!=[] or value.get('company_preference') is not False
            or value.get('promotion')!=PROMOTION or value.get('evidence_boundary') not in (None,BOUNDARY)
            or not isinstance(evidence,dict) or not set(evidence)<={'run','video_sha256','quality_sha256'}):continue
        selected.append({k:row[k] for k in ['path','sha256','scope']})
    result={'sources':sorted(source_hashes),'records':selected,'count':len(selected),
            'scope':'Only audited generated placeholder records. Preserve original bytes, case assets, language scopes, quality states and unknown billing.'}
    return {**result,'fingerprint':object_hash(result)}


def execute(root, source_hashes, expected, reviewed_by, origin):
    root=Path(root).resolve();planned=preview(root,source_hashes)
    require(expected==planned['fingerprint'],'Empty-reflection preview changed; inspect the new preview')
    require(bool(reviewed_by) and bool(origin),'An attributed structural review is required')
    results=[]
    for source in planned['records']:
        spec={'source':{'path':source['path'],'sha256':source['sha256']},'previous_review':None,
              'review_type':'developer_review','reviewed_by':reviewed_by,'origin':origin,'resolution':'rejected',
              'reason':'Reject only treating the exact autogenerated placeholder as reusable knowledge. It contains no actionable lesson. This is not a rejection or reapproval of its video; its linked evidence and quality issues remain historical facts.',
              'targets':[],'adopted_parts':[],
              'retained_parts':['Original source, locale, video/quality hashes, outcome, case pointer and restrictions remain unchanged. Source-family findings are curated separately; unresolved media quality and charges remain outside this closure.'],
              'all_material_accounted':True,'remaining_disposition':'historical_only','next_action':'historical_record_only'}
        decision=review(spec,root)
        archived=None
        if source['path'].startswith('knowledge/candidates/'):
            ready=archive_preview(source['path'],root)
            archived=archive(source['path'],ready['fingerprint'],root)
        results.append({'source':source,'review':decision,'archive':archived})
    refresh(root)
    return {'reviewed':len(results),'archived_public':sum(bool(r['archive']) for r in results),'results':results,
            'scope':'Knowledge bookkeeping only. No source videos, delivery packages, cases or request ledgers removed.'}
